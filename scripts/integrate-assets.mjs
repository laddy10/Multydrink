import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import sharp from 'sharp';

// Convert only supplied files. No cropping, retouching, compositing or source overwrites.
const sources = [
  ['individual', 'producto/caja-principal', 'Caja individual MultyDrink, imagen suministrada del empaque'],
  ['alternateBox', 'producto/caja-alternativa', 'Vista alternativa suministrada de la caja MultyDrink'],
  ['nutritionLabel', 'nutricion/tabla-nutricional', 'Etiqueta nutricional e ingredientes de MultyDrink; transcripción de datos principales disponible debajo'],
  ['enfoque', 'lifestyle/trabajo', 'Mujer en su escritorio con una bebida durante una pausa de trabajo'],
  ['energia', 'lifestyle/actividad-fisica', 'Escena de ciclismo al aire libre con la caja MultyDrink en primer plano'],
  ['memoria', 'lifestyle/estudio', 'Estudiante con cuaderno, bebida y caja MultyDrink sobre la mesa'],
  ['bienestar', 'lifestyle/bienestar', 'Mujer estirándose en una terraza, con una bebida y caja MultyDrink'],
  ['comparisonFirst', 'lifestyle/antes-cansancio', 'Mujer con la mano en la frente ante un computador, en una jornada de trabajo'],
  ['comparisonSecond', 'lifestyle/despues-energia', 'La misma escena de escritorio, con la mujer sonriendo, una bebida, caja y sobre MultyDrink'],
  ['composition', 'ingredientes/composiciones', 'Composición suministrada con café, uva, agave, ganoderma, té, caja y bebida MultyDrink'],
];
const directory = 'assets/multydrink/optimized';
await mkdir(directory, { recursive: true });
const catalog = {}, inventory = [];
for (const [key, name, alt] of sources) {
  const original = `assets/multydrink/${name}.png`;
  const input = await readFile(original);
  const metadata = await sharp(input).metadata();
  const fullWidth = Math.min(metadata.width, key === 'nutritionLabel' ? metadata.width : 1280);
  const widths = key === 'nutritionLabel' ? [fullWidth] : [...new Set([160, 480, Math.min(960, fullWidth), fullWidth])];
  const variants = [];
  for (const width of widths) {
    const src = `${directory}/${name.split('/').at(-1)}-${width}.webp`;
    const info = await sharp(input).resize({ width, withoutEnlargement: true })
      .webp(key === 'nutritionLabel' ? { lossless: true } : { quality: 88, alphaQuality: 100 })
      .toFile(src);
    variants.push({ src, width: info.width, height: info.height, bytes: info.size });
  }
  const full = variants.at(-1);
  catalog[key] = { src: full.src, alt, width: full.width, height: full.height,
    variants: variants.map(({ src, width }) => ({ src, width })), thumbnail: variants[0].src };
  inventory.push({ key, original, originalBytes: input.length, sha256: createHash('sha256').update(input).digest('hex'), originalWidth: metadata.width, originalHeight: metadata.height, variants });
}
await writeFile('src/media-catalog.js', '// Generated by scripts/integrate-assets.mjs from supplied originals.\nexport const approvedImages = ' + JSON.stringify(catalog, null, 2) + ';\n');
await writeFile('docs/asset-inventory.json', JSON.stringify(inventory, null, 2) + '\n');
console.log(`Integrated ${inventory.length} supplied images into ${inventory.reduce((n, item) => n + item.variants.length, 0)} WebP files. Originals unchanged.`);
